#!/usr/bin/env node
/**
 * build-admin-css — compiles the admin's Tailwind v4 stylesheet (src/app/globals.css) into plain CSS
 * (src/app/globals.compiled.css), which src/app/layout.tsx imports.
 *
 * Why not let the bundler run Tailwind: Turbopack runs CSS loaders (Tailwind, PostCSS) in separate
 * Node.js worker processes. Hostinger's build machines kill those workers ("node process exited before
 * we could connect to it"), so the build failed on the first stylesheet. Compiling here, in the
 * prebuild step, leaves Turbopack only plain CSS, which it handles natively with no workers.
 *
 * Runs on predev/prebuild (`npm run css:admin`). `--watch` keeps recompiling while you edit admin
 * code (scripts/dev.mjs starts it next to `next dev`). The output is committed, so a deploy still
 * builds if compiling here ever fails: the script then keeps the last good file and only warns.
 *
 * The admin tokens (core §I.6, DES-§16.2) are not written in globals.css: src/lib/admin-theme/generate.ts computes
 * them in OKLCH for light and dark × [data-surface="tenant" | "console"], with the radius ladder, motion and density,
 * and this script appends its `adminTokensCss()` to the compiled file (loaded through tsx's API, no bundler loader).
 * test:admin-tokens fails when the committed output does not carry the generator's current blocks.
 */
import { existsSync, readFileSync, watch, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src", "app", "globals.css");
const OUT = join(ROOT, "src", "app", "globals.compiled.css");
const TOKENS = join(ROOT, "src", "lib", "admin-theme", "generate.ts");
const WATCH = process.argv.includes("--watch");

const HEADER =
  "/* GENERATED by scripts/build-admin-css.mjs from src/app/globals.css (Tailwind v4) and src/lib/admin-theme/generate.ts. Do not edit. */\n";

/** The generated token blocks. A fresh import per run, so `--watch` picks up an edited generator. */
async function tokensCss(minify) {
  const { tsImport } = await import("tsx/esm/api");
  const mod = await tsImport(`${pathToFileURL(TOKENS).href}?v=${Date.now()}`, import.meta.url);
  const render = mod.adminTokensCss ?? mod.default?.adminTokensCss;
  const css = typeof render === "function" ? render({ minify }) : null;
  if (typeof css !== "string" || !css.includes("--background")) throw new Error("admin-theme: adminTokensCss() returned no tokens");
  return css;
}

async function compileOnce() {
  const { compile, optimize } = await import("@tailwindcss/node");
  const { Scanner } = await import("@tailwindcss/oxide");
  const css = readFileSync(SRC, "utf8");
  const compiler = await compile(css, {
    from: SRC,
    base: dirname(SRC),
    shouldRewriteUrls: true,
    onDependency: () => {},
  });
  const sources = (
    compiler.root === "none"
      ? []
      : compiler.root === null
        ? [{ base: ROOT, pattern: "**/*", negated: false }]
        : [{ ...compiler.root, negated: false }]
  ).concat(compiler.sources);
  // automatic source detection skips CSS files, so the output never feeds its own classes back
  const candidates = new Scanner({ sources }).scan();
  const built = compiler.build(candidates);
  const { code } = optimize(built, { minify: !WATCH });
  // appended after Tailwind's output, unlayered like the hand-written blocks they replace, and not run through
  // lightningcss, which would rewrite the oklch() values the token check compares against
  return HEADER + code + (await tokensCss(!WATCH));
}

async function run() {
  const started = Date.now();
  try {
    const next = await compileOnce();
    const prev = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
    if (prev !== next) writeFileSync(OUT, next);
    console.log(
      `[admin-css] ${relative(ROOT, OUT)} ${prev === next ? "unchanged" : "written"} ` +
        `(${(next.length / 1024).toFixed(1)} KB, ${Date.now() - started} ms)`,
    );
    return true;
  } catch (err) {
    if (existsSync(OUT) && !WATCH) {
      console.warn(`[admin-css] compile failed — keeping the committed ${relative(ROOT, OUT)}:`, err);
      return true;
    }
    console.error("[admin-css] compile failed:", err);
    return false;
  }
}

// a recognisable line in the Hostinger build log: if it is missing, the host built an older commit
if (!WATCH) console.log("[admin-css] COD Studio build: admin Tailwind precompiled, Turbopack runs without loaders");
const ok = await run();
if (!WATCH) process.exit(ok ? 0 : 1);

// --watch: recompile when admin sources change (class names live in .ts/.tsx, tokens in .css)
let timer = null;
const relevant = (f) => f && /\.(tsx?|jsx?|mdx?|css)$/.test(f) && !f.endsWith("globals.compiled.css");
watch(join(ROOT, "src"), { recursive: true }, (_event, file) => {
  if (!relevant(String(file ?? ""))) return;
  clearTimeout(timer);
  timer = setTimeout(run, 150);
});
console.log("[admin-css] watching src/ for changes");
